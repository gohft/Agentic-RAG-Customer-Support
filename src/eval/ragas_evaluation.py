import logging
from typing import TypedDict

import pandas as pd
import torch
import litellm
# possible errors from LLM wrapped in ragas llm_factory
from instructor.core import IncompleteOutputException, InstructorRetryException
from ragas.llms import llm_factory
from ragas.embeddings import HuggingFaceEmbeddings
from ragas.metrics.collections import Faithfulness, AnswerCorrectness

from src.utils.my_logging import setup_logging
from src.utils.load_config import load_config

setup_logging()
logger = logging.getLogger("eval")


class ColumnMapDict(TypedDict):
    """
    Dictionary of the columns names to use for evaluation.

    Attributes:
        actual_classification: Column name of the ground truth classification of query.
        agent_classification: Column name of the classification of query by classification node.
        question: Column name of the query.
        response: Column name of response generated by customer support node for the query.
        context: Column name of the retrieved documents from RAG tool to help response to query.
        reference: Column name of the ground truth response to query.
    """
    actual_classification: str
    agent_classification: str
    question: str
    response: str
    context: str
    reference: str


class RagasEvaluation:
    """
    Use RAGAS to evaluate the Faithfulness and answer correctness of the RAG tool search,
    using an Ollama LLM as judge and a HuggingFace embedding model.
    """

    def __init__(self, config_path: str = 'config/eval/ragas_evaluation.yaml'):

        self.config_path = config_path
        self.config = load_config(self.config_path)
        logger.info(f"Configuration loaded from {self.config_path}")

        self.ollama_url = self.config["ollama_url"]
        self.judge_model_cfg = self.config["judge_model"]
        self.embedding_model_name = self.config["embedding_model"]
        self.doc_separator = self.config["doc_separator"]

        # set device for huggingface
        self.device = "cuda" if torch.cuda.is_available() else "cpu"

        # lazy load models and metrics, set when first accessed
        # judge llm will be used by both metric
        # prevent reloading of models to reduce latency
        self._judge_llm = None
        self._embedding_model = None
        self._faithfulness_metric = None
        self._correctness_metric = None

    @property
    def judge_llm(self):
        """Set the model to be used as LLM-as-a-judge when called."""
        if self._judge_llm is None:
            self._judge_llm = llm_factory(
                provider="litellm",
                client=litellm.acompletion,  # use acompletion for async call
                api_base=self.ollama_url,
                extra_body={"think": False},  # non thinking mode
                model=self.judge_model_cfg["model"],
                **self.judge_model_cfg["parameters"],
            )
            logger.info(f"Judge LLM created: {self.judge_model_cfg["model"]}.")
        return self._judge_llm

    @property
    def embedding_model(self):
        """Set the embedding model to be used in AnswerCorrectness metric when called."""
        if self._embedding_model is None:
            self._embedding_model = HuggingFaceEmbeddings(
                model=self.embedding_model_name,
                use_api=False,
                device=self.device,
            )
            logger.info(f"Embedding model created: {self.embedding_model_name}.")
        return self._embedding_model

    @property
    def faithfulness_metric(self) -> Faithfulness:
        """
        Set the Faithfulness metric to be used to check 
        if LLM only use provided context for response generation,
        with no hallucination.
        """
        if self._faithfulness_metric is None:
            self._faithfulness_metric = Faithfulness(llm=self.judge_llm)
        return self._faithfulness_metric

    @property
    def correctness_metric(self) -> AnswerCorrectness:
        """
        Set the AnswerCorrectness metric to evaluate how correct a response is against a reference answer.
        Needs embedding model since part of the score includes semantic similarity.
        Use default ratio of factuality (0.75) and semantic similarity (0.25) to get overall score.
        """
        if self._correctness_metric is None:
            self._correctness_metric = AnswerCorrectness(
                llm=self.judge_llm,
                embeddings=self.embedding_model,
            )
        return self._correctness_metric

    @staticmethod
    def _validate_columns(input_df: pd.DataFrame, column_map: ColumnMapDict) -> None:
        """
        Check that every column name referenced in column_map exists in input_df.

        Raises:
            ValueError: If any referenced column is missing from input_df.
        """
        missing = [col for col in column_map.values() if col not in input_df.columns]
        if missing:
            raise ValueError(f"Column(s) {missing} not found in input_df.")

    @staticmethod
    def _classification_score(row: pd.Series, column_map: ColumnMapDict) -> int:
        """Return 1 if actual and agent classification match for the row, else 0."""
        actual = row[column_map["actual_classification"]]
        agent = row[column_map["agent_classification"]]
        return 1 if actual == agent else 0

    def _as_context_list(self, context_value) -> list[str]:
        """
        Convert a context value to the list[str] RAGAS Faithfulness expects.
        The RAG pipeline stores retrieved docs as one string joined with
        self.doc_separator. Break the long string back into substrings.
        """
        if isinstance(context_value, list):
            return context_value
        return [chunk for chunk in str(context_value).split(self.doc_separator) if chunk.strip()]

    @staticmethod
    def _safe_score(metric, **kwargs) -> float | None:
        """
        Call metric.score(**kwargs) and return its value, or None if the judge LLM
        call failed for this attempt due to either 
        i) IncompleteOutputException (LLM output exceed max tokens limit)
        ii) InstructorRetryException (output does not match schema after exhausting retries)

        Args:
            metric: Ragas metric object.
            kwargs: key value pair of input for metric to get score.
        
        Returns:
            Metric score or None if error occurs when metric tries to get score.
        """
        try:
            return metric.score(**kwargs).value
        except (IncompleteOutputException, InstructorRetryException) as e:
            logger.warning(f"{metric.name} scoring failed with {type(e).__name__}: {e}. Skipping this evaluation attempt.")
            return None

    def _faithfulness_score(self, question: str, response: str, context_value, number_of_eval: int,) -> float | None:
        """
        Score Faithfulness number_of_eval times and return the average.
        Repeated scoring since LLM is non-deterministic.
        Require the question which is not being evaluated to provide the context of the response/context.

        Args:
            question: Question provided to LLM for response.
            response: LLM generated response for the question after using RAG tool to get relevant docs.
            context_value: String formed from concatenation of all docs retrieved from RAG tool.
            number_of_eval: Number of times to repeat the scoring.

        Returns:
            Average faithfulness score after repeated evaluation or 
            None if every metric evaluation had an error.
        """
        metric = self.faithfulness_metric

        # convert context to list of strings (required as input)
        contexts = self._as_context_list(context_value)

        # score faithfullness number_of_eval times
        scores = [
            self._safe_score(
                metric,
                user_input=question,
                response=response,
                retrieved_contexts=contexts,
            )
            for _ in range(number_of_eval)
        ]

        # return None if no score available due to errors
        valid_scores = [score for score in scores if score is not None]
        return sum(valid_scores) / len(valid_scores) if valid_scores else None

    def _correctness_score(self, question: str, response: str, reference: str, number_of_eval: int,) -> float | None:
        """
        Score AnswerCorrectness number_of_eval times and return the average.
        Repeated scoring since LLM is non-deterministic.
        Require the question which is not being evaluated to provide the context of the response/context.

        Args:
            question: Question provided to LLM for response.
            response: LLM generated response for the question after using RAG tool to get relevant docs.
            reference: Ground truth response to the question which will be used as comparison against the LLM response.
            number_of_eval: Number of times to repeat the scoring.

        Returns:
            Average correctness score after repeated evaluation, ignoring any
            attempts that failed with a judge LLM error. None if every attempt failed.
        """
        metric = self.correctness_metric
        scores = [
            self._safe_score(
                metric,
                user_input=question,
                response=response,
                reference=reference,
            )
            for _ in range(number_of_eval)
        ]
        # return None if no score available due to errors
        # take average since LLM evaluation is not deterministic
        valid_scores = [score for score in scores if score is not None]
        return sum(valid_scores) / len(valid_scores) if valid_scores else None

    def evaluate_faithfulness_correctness(
        self,
        df: pd.DataFrame,
        number_of_eval: int,
        dictionary_columns_name: ColumnMapDict,
    ):
        """
        Evaluate classification accuracy, Faithfulness and AnswerCorrectness for each
        row of dataframe, add the scores as new columns and return their aggregates.

        Args:
            df: Dataframe to evaluate.
            number_of_eval: Number of times to compute each RAGAS metric per row,
                averaged to get that row's score.
            dictionary_columns_name: Maps the logical fields (question, response,
                context, reference, actual/agent classification) to the actual
                column names in csv_file.

        Returns:
            tuple: (updated input_df with additional columns of metric scores,
            classification_score average, faithfulness_score statistics,
            correctness_score statistics).
        """
        input_df = df.copy()

        # ensure required columns are present in csv
        self._validate_columns(input_df, dictionary_columns_name)

        # new columns to add
        classification_scores = []
        faithfulness_scores = []
        correctness_scores = []

        for i, row in input_df.iterrows():
            logger.info(f"Evaluating row {i}.")
            classification_scores.append(self._classification_score(row, dictionary_columns_name))

            # no retrieved docs or no response, do not evaluate faithfulness
            if pd.isna(row[dictionary_columns_name["response"]]) or pd.isna(row[dictionary_columns_name["context"]]):
                faithfulness_scores.append(None)
            else:
                faithfulness_scores.append(self._faithfulness_score(
                    row[dictionary_columns_name["question"]],
                    row[dictionary_columns_name["response"]],
                    row[dictionary_columns_name["context"]],
                    number_of_eval,
                ))
            # no reference or no response, do not evaluate correctness
            if pd.isna(row[dictionary_columns_name["response"]]) or pd.isna(row[dictionary_columns_name["reference"]]):
                correctness_scores.append(None)
            else:
                correctness_scores.append(self._correctness_score(
                    row[dictionary_columns_name["question"]],
                    row[dictionary_columns_name["response"]],
                    row[dictionary_columns_name["reference"]],
                    number_of_eval,
                ))

        input_df["classification_score"] = classification_scores
        input_df["faithfulness_score"] = faithfulness_scores
        input_df["correctness_score"] = correctness_scores

        logger.info(f"Evaluation completed for input dataframe. Outputing scores of averaging {number_of_eval} evaluation.")

        # statistic ignore None values
        classification_avg = input_df["classification_score"].mean()
        faithfulness_stats = input_df["faithfulness_score"].describe()
        correctness_stats = input_df["correctness_score"].describe()

        return input_df, classification_avg, faithfulness_stats, correctness_stats


if __name__ == "__main__":
    from dotenv import load_dotenv
    from src.database.postgres_connection import PostgresConnection

    load_dotenv()

    # get the dataframe from postgreSQL DB to evaluate
    db = PostgresConnection()
    TABLE_NAME = "test_dataset"
    df = db.download_table(TABLE_NAME)

    # set the evaluator and do the evaluations
    evaluator = RagasEvaluation()

    column_map: ColumnMapDict = {
        "actual_classification": "classification",
        "agent_classification": "agent_classification",
        "question": "user_input_email_format",  # in email format
        "response": "agent_response",
        "context": "retrieved_docs",
        "reference": "reference_email_format",  # in email format
    }

    # repeat evaluation for 3 times
    update_df, classification_avg, faithfulness_stats, correctness_stats = evaluator.evaluate_faithfulness_correctness(
        df,
        number_of_eval=3,
        dictionary_columns_name=column_map,
    )

    # save the evaluated result 
    evaluated_df_csv = "test_dataset_evaluated.csv"
    update_df.to_csv(evaluated_df_csv, index=False)
    logger.info(f"Saving the evaluation result in {evaluated_df_csv}.")

    logger.info(f"Classification accuracy: {classification_avg}")
    logger.info(f"Faithfulness stats:\n{faithfulness_stats}")
    logger.info(f"Correctness stats:\n{correctness_stats}")
